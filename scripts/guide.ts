// Bundles measurements for the AI settings (#37): `pnpm bench` writes eval/<stamp>-bench.json and `pnpm eval` writes
// eval/<stamp>-<model>.json; this joins the newest run per model into src/modelGuideData.ts. Run both, then `pnpm guide`.
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { z } from "zod";
import { modelKey, type Measurement } from "../src/modelGuide.ts";

const dir = fileURLToPath(new URL("../eval/", import.meta.url));
const files = existsSync(dir) ? readdirSync(dir).filter((f) => f.endsWith(".json")) : [];

// Reports are read by shape, not by filename alone: a report from an older script is skipped, never half-read.
const Bench = z.object({
  meta: z.object({ date: z.string().min(10), hardware: z.string().min(1) }),
  rows: z.array(z.object({
    model: z.string().min(1), "first sentence (ms)": z.number().optional(), "reply (ms)": z.number().optional(), error: z.string().optional(),
  })),
});
const EvalReport = z.object({
  meta: z.object({
    model: z.string().min(1), date: z.string().min(10), hardware: z.string().min(1),
    summary: z.object({ items_expected: z.number().int().nonnegative() }),
  }),
  cases: z.array(z.object({ items: z.array(z.object({ failed: z.array(z.string()) })).optional() })),
});
type Bench = z.infer<typeof Bench>;
type EvalReport = z.infer<typeof EvalReport>;

const skipped: string[] = [];
const read = (f: string): unknown => {
  try { return JSON.parse(readFileSync(dir + f, "utf8")); }
  catch (e) { skipped.push(`eval/${f}: not JSON (${(e as Error).message.slice(0, 80)})`); return null; }
};

/** Newest report per model, so a rerun replaces an older one instead of blending them. */
function newest<T extends { meta: { date: string } }>(best: Map<string, T>, model: string, r: T) {
  const old = best.get(model);
  if (!old || r.meta.date > old.meta.date) best.set(model, r);
}

/** Parses one report, noting why it was skipped; null means it cannot be used. */
function parse<S extends z.ZodType>(f: string, schema: S): z.infer<S> | null {
  const raw = read(f);
  if (raw === null) return null;
  const parsed = schema.safeParse(raw);
  if (parsed.success) return parsed.data;
  const issue = parsed.error.issues[0];
  skipped.push(`eval/${f}: ${issue ? `${issue.path.join(".") || "report"}: ${issue.message}` : "unexpected shape"}`);
  return null;
}

const benches = new Map<string, Bench>(), evals = new Map<string, EvalReport>();
for (const f of files) {
  if (f.endsWith("-bench.json")) {
    const r = parse(f, Bench);
    if (r) for (const row of r.rows) {
      const k = modelKey(row.model);
      if (k) newest(benches, k, r);
    }
  } else {
    const r = parse(f, EvalReport);
    if (r && modelKey(r.meta.model)) newest(evals, modelKey(r.meta.model), r);
  }
}

const rows: Measurement[] = [];
for (const [key, bench] of benches) {
  const row = bench.rows.find((x) => modelKey(x.model) === key), report = evals.get(key);
  if (!row) continue;
  const say = row["first sentence (ms)"], reply = row["reply (ms)"];
  if (typeof say !== "number" || typeof reply !== "number") {
    skipped.push(`${row.model}: no latency in the newest bench (${row.error?.slice(0, 60) ?? "no times"})`);
    continue;
  }
  // The two reports must agree on the machine: latency and quality are hardware-specific, and an unrecorded machine
  // (reports before scripts/eval.ts wrote one) cannot be claimed to be the bench's.
  if (!report) { skipped.push(`${row.model}: no usable eval report`); continue; }
  if (report.meta.hardware !== bench.meta.hardware) {
    skipped.push(`${row.model}: eval ran on "${report.meta.hardware}", bench on "${bench.meta.hardware}" — re-run pnpm eval`);
    continue;
  }
  // Errored cases are in the denominator (items_expected), so a model cannot look better by failing.
  const items = report.cases.flatMap((c) => c.items ?? []);
  const passed = items.filter((i) => !i.failed.length).length;
  const total = report.meta.summary.items_expected || items.length;
  if (!total) { skipped.push(`${row.model}: eval report has no expected items`); continue; }
  rows.push({
    model: row.model, sayMs: Math.round(say), replyMs: Math.round(reply),
    quality: Math.round((passed / total) * 100), cases: report.cases.length, hardware: bench.meta.hardware,
    measured: bench.meta.date.slice(0, 10), evaluated: report.meta.date.slice(0, 10),
  });
}
for (const [key, report] of evals) if (!benches.has(key)) skipped.push(`${report.meta.model}: no usable bench report`);

rows.sort((a, b) => a.model.localeCompare(b.model));
for (const s of skipped) console.error(`skipped ${s}`);
if (!rows.length) throw new Error("no model has both a bench and an eval report from the same machine; run pnpm bench and pnpm eval first");

const out = `// Generated by \`pnpm guide\` from the \`pnpm bench\` and \`pnpm eval\` reports in eval/. Do not edit by hand.
// Each row names the machine and both run dates, which the AI settings show with the numbers.
import type { Measurement } from "./modelGuide";

export const MEASURED: Measurement[] = [
${rows.map((r) => `  { model: ${JSON.stringify(r.model)}, sayMs: ${r.sayMs}, replyMs: ${r.replyMs}, quality: ${r.quality}, cases: ${r.cases}, hardware: ${JSON.stringify(r.hardware)}, measured: ${JSON.stringify(r.measured)}, evaluated: ${JSON.stringify(r.evaluated)} },`).join("\n")}
];
`;
writeFileSync(fileURLToPath(new URL("../src/modelGuideData.ts", import.meta.url)), out);
console.log(`src/modelGuideData.ts: ${rows.length} measured models${skipped.length ? `, ${skipped.length} skipped` : ""}`);
