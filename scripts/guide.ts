// Bundles measurements for the AI settings (#37): `pnpm bench` writes eval/<stamp>-bench.json and `pnpm eval` writes
// eval/<stamp>-<model>.json; this joins the newest run per model into src/modelGuideData.ts. Run both, then `pnpm guide`.
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import type { Measurement } from "../src/modelGuide.ts";

const dir = new URL("../eval/", import.meta.url).pathname;
const files = existsSync(dir) ? readdirSync(dir).filter((f) => f.endsWith(".json")) : [];
const read = (f: string) => { try { return JSON.parse(readFileSync(dir + f, "utf8")); } catch { return null; } };

type Bench = {
  meta: { date: string; hardware: string };
  rows: { model: string; "first sentence (ms)"?: number; "reply (ms)"?: number; error?: string }[];
};
type EvalReport = {
  meta: { model: string; date: string; summary: { items_expected: number } };
  cases: { items?: { failed: string[] }[] }[];
};

/** Newest report per model, so a rerun replaces an older one instead of blending them. */
function newest<T extends { meta: { date: string } }>(best: Map<string, T>, model: string, r: T) {
  const old = best.get(model);
  if (!old || r.meta.date > old.meta.date) best.set(model, r);
}

const benches = new Map<string, Bench>(), evals = new Map<string, EvalReport>();
for (const f of files) {
  const r = read(f);
  if (!r?.meta) continue;
  if (f.endsWith("-bench.json")) for (const row of (r as Bench).rows) newest(benches, row.model, r);
  else if (r.meta.model) newest(evals, r.meta.model, r as EvalReport);
}

const rows: Measurement[] = [];
for (const [model, bench] of benches) {
  const row = bench.rows.find((x) => x.model === model), report = evals.get(model);
  if (!report || typeof row?.["first sentence (ms)"] !== "number" || typeof row["reply (ms)"] !== "number") continue;
  // Errored cases are in the denominator (items_expected), so a model cannot look better by failing.
  const items = report.cases.flatMap((c) => c.items ?? []);
  const passed = items.filter((i) => !i.failed.length).length;
  const total = report.meta.summary.items_expected || items.length;
  if (!total) continue;
  rows.push({
    model, sayMs: Math.round(row["first sentence (ms)"]), replyMs: Math.round(row["reply (ms)"]),
    quality: Math.round((passed / total) * 100), cases: report.cases.length,
    hardware: bench.meta.hardware, measured: bench.meta.date.slice(0, 10),
  });
}
rows.sort((a, b) => a.model.localeCompare(b.model));
if (!rows.length) throw new Error("no model has both a bench and an eval report; run pnpm bench and pnpm eval first");

const out = `// Generated by \`pnpm guide\` from the \`pnpm bench\` and \`pnpm eval\` reports in eval/. Do not edit by hand.
// Each row names the machine and date it ran on, which the AI settings show with the numbers.
import type { Measurement } from "./modelGuide";

export const MEASURED: Measurement[] = [
${rows.map((r) => `  { model: ${JSON.stringify(r.model)}, sayMs: ${r.sayMs}, replyMs: ${r.replyMs}, quality: ${r.quality}, cases: ${r.cases}, hardware: ${JSON.stringify(r.hardware)}, measured: ${JSON.stringify(r.measured)} },`).join("\n")}
];
`;
writeFileSync(new URL("../src/modelGuideData.ts", import.meta.url).pathname, out);
console.log(`src/modelGuideData.ts: ${rows.length} measured models`);
